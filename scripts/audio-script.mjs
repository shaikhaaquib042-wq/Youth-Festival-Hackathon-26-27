// Generates docs/audio-script.md — the text to record for each voice clip, per language.
// Run: node scripts/audio-script.mjs   (re-run after changing any spoken string)
import { writeFileSync } from 'node:fs';
import { CLIPS, NUMBER_WORDS } from '../src/i18n/clips.js';
const tables = Object.fromEntries(await Promise.all(['en', 'mr', 'hi', 'kn', 'te'].map(async (l) => [l, (await import(`../src/i18n/${l}.js`)).default])));

const DEV = '०१२३४५६७८९';
const toInt = (s) => parseInt([...s].map((c) => (DEV.includes(c) ? DEV.indexOf(c) : c)).join(''), 10);
const spoken = (lang, key, vars = {}) => {
  let s = (tables[lang][key] ?? tables.en[key]).replace(/\{(\w+)\}/g, (_, k) => vars[k]);
  s = s.replace(/[0-9०-९]+/g, (m) => NUMBER_WORDS[lang]?.[toInt(m)] ?? m);
  return lang === 'kn' ? s.replaceAll('ಎಂಟುಕ್ಕೆ', 'ಎಂಟಕ್ಕೆ') : s; // Kannada sandhi: entu + kke → entakke
};

const LANGS = [
  ['mr', 'Marathi (मराठी)', 'PRIORITY — no Marathi voice on the demo Mac'],
  ['hi', 'Hindi (हिन्दी)', 'Maharashtra + Telangana packs'],
  ['kn', 'Kannada (ಕನ್ನಡ)', 'Karnataka pack'],
  ['te', 'Telugu (తెలుగు)', 'Karnataka + Telangana packs'],
];

let md = `# Mausam Mitra — voice clip script

Generated by \`node scripts/audio-script.mjs\` from the app's translation tables — the recordings must match the on-screen text.
${CLIPS.length} clips × ${LANGS.length} languages. Numbers are written as words so they are read in the right language.

## How to hand this to Gemini
Paste ONE language section at a time with this instruction:

> Generate a separate audio file for each line below. Voice: calm, clear, friendly adult; a native speaker of the language; slightly slow, like a public-safety announcement; no background music. Read the text exactly as written — do not translate or add words. Name each file exactly as given in the first column (e.g. \`heat-water.mp3\`). Format: MP3, mono.

## Where the files go
\`public/audio/<lang>/<file>.mp3\` — e.g. \`public/audio/mr/heat-water.mp3\`. Then add the language code to \`CONFIG.HEAT.AUDIO_CLIP_LANGS\` in \`config.js\` (e.g. \`['mr']\`). Missing or broken files fall back to the device voice automatically.

## English reference (what each clip means — do not record)
| File | Meaning |
|---|---|
${CLIPS.map((c) => `| \`${c.id}.mp3\` | ${spoken('en', c.key, c.vars)} |`).join('\n')}
`;
for (const [l, name, note] of LANGS) {
  md += `\n## ${name} — folder \`public/audio/${l}/\`\n_${note}_\n\n| File | Text to speak |\n|---|---|\n`;
  md += CLIPS.map((c) => `| \`${c.id}.mp3\` | ${spoken(l, c.key, c.vars)} |`).join('\n') + '\n';
}
writeFileSync(new URL('../docs/audio-script.md', import.meta.url), md);
console.log(`wrote docs/audio-script.md: ${CLIPS.length} clips x ${LANGS.length} languages`);
