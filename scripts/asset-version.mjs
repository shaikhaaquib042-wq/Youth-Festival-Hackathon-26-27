// Writes packages/config/src/asset-version.ts with a short hash of the shared, unhashed assets
// (/styles/raasta.css, /styles/flow.css, /js/locate.js). Pages and the Worker link them as ?v=<hash>, so browsers
// fetch a fresh copy whenever they change instead of showing an old cached style. Runs before every web build.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const ASSET_FILES = ["apps/web/public/styles/raasta.css", "apps/web/public/styles/flow.css", "apps/web/public/js/locate.js"];
const h = createHash("sha256");
for (const f of ASSET_FILES) h.update(readFileSync(join(root, f), "utf8").replace(/\r\n/g, "\n"));
const v = h.digest("hex").slice(0, 10);
const out = join(root, "packages/config/src/asset-version.ts");
const body = `// Generated by scripts/asset-version.mjs. Do not edit by hand.\nexport const ASSET_V = "${v}";\n`;
let old = "";
try { old = readFileSync(out, "utf8"); } catch {}
if (old !== body) writeFileSync(out, body);
console.log(`asset version ${v}`);
